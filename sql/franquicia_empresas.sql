create table if not exists public.franquicia_empresas (
    id bigint generated by default as identity primary key,
    rut_empresa text not null unique,
    razon_social text,
    franquicia_anual numeric(14, 2) not null default 0,
    usado numeric(14, 2) not null default 0,
    disponible numeric(14, 2) generated always as (
        greatest(franquicia_anual - usado, 0)
    ) stored,
    "año" integer not null default extract(year from current_date)::int,
    updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at_franquicia()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists franquicia_empresas_updated_at on public.franquicia_empresas;

create trigger franquicia_empresas_updated_at
before update on public.franquicia_empresas
for each row
execute function public.set_updated_at_franquicia();
