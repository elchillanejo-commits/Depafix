-- Tablas para precios dinámicos del cotizador
-- material_catalogo: catálogo de materiales e insumos con precio base
-- partida_receta: receta de partidas que combina materiales con cantidades

create table if not exists public.materiales_catalogo (
    codigo text primary key,
    nombre text not null,
    unidad text not null default 'm2',
    precio_base_clp numeric not null default 0,
    es_material boolean not null default true,
    componente_material boolean not null default true,
    proveedor text,
    fecha_actualizacion timestamptz not null default now(),
    activo boolean not null default true
);

create table if not exists public.partida_receta (
    codigo_partida text primary key,
    nombre_partida text not null,
    descripcion text,
    unidad_medida text not null default 'm2',
    rendimiento numeric not null default 1,
    es_activa boolean not null default true,
    fecha_creacion timestamptz not null default now(),
    fecha_actualizacion timestamptz not null default now()
);

create table if not exists public.partida_receta_detalle (
    id bigint generated by default as identity primary key,
    codigo_partida text not null references public.partida_receta(codigo_partida) on delete cascade,
    codigo_material text not null references public.materiales_catalogo(codigo) on delete cascade,
    cantidad numeric not null default 0,
    nota text,
    created_at timestamptz not null default now()
);

create index if not exists partida_receta_detalle_partida_idx
    on public.partida_receta_detalle (codigo_partida);

create index if not exists materiales_catalogo_activo_idx
    on public.materiales_catalogo (activo);

