create extension if not exists vector;

create table if not exists public.coach_otec (
    id bigint generated by default as identity primary key,
    contenido text not null,
    metadata jsonb not null default '{}'::jsonb,
    embedding vector(384) not null,
    hash_origen text,
    created_at timestamptz not null default now()
);

create index if not exists coach_otec_embedding_idx
    on public.coach_otec using hnsw (embedding vector_cosine_ops);

create unique index if not exists coach_otec_hash_origen_idx
    on public.coach_otec (hash_origen);

create index if not exists coach_otec_tipo_idx
    on public.coach_otec ((metadata->>'tipo'));

create or replace function public.match_coach_otec(
    query_embedding vector(384),
    match_threshold double precision default 0.0,
    match_count integer default 6,
    p_tipo text default null
)
returns table (
    id bigint,
    contenido text,
    metadata jsonb,
    similarity double precision
)
language sql
stable
as $$
    select
        c.id,
        c.contenido,
        c.metadata,
        1 - (c.embedding <=> query_embedding) as similarity
    from public.coach_otec c
    where (p_tipo is null or c.metadata->>'tipo' = p_tipo)
      and (1 - (c.embedding <=> query_embedding)) >= match_threshold
    order by c.embedding <=> query_embedding
    limit match_count;
$$;
