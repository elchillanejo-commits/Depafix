-- Tabla cursos_sence — ficha de curso para aprobación y ejecución SENCE
-- Aplicar en el SQL Editor de Supabase (o psql).
-- Ejemplo de estado: 'borrador' -> 'enviado_sence' -> 'aprobado' -> 'ejecutando' -> 'liquidado'

create table if not exists public.cursos_sence (
    id bigint generated by default as identity primary key,

    codigo_sence text not null unique,          -- ej: 1238088484
    nombre_curso text not null,
    modalidad text,                              -- Presencial / E-learning / Híbrido / BMA / Abp
    horas_cronologicas integer,
    numero_participantes integer,
    competencia text,                            -- competencia laboral declarada

    aprendizajes_esperados jsonb not null default '[]'::jsonb,
    contenidos jsonb not null default '[]'::jsonb,
    relatores jsonb not null default '[]'::jsonb,  -- ej: [{"nombre":"Ana P.","rut":"12.345.678-9"}]

    costo_facilitador numeric(12, 2) not null default 0,
    costo_infraestructura numeric(12, 2) not null default 0,
    costo_materiales numeric(12, 2) not null default 0,
    costo_utilidades numeric(12, 2) not null default 0,
    total_curso numeric(12, 2) not null default 0,

    estado text not null default 'borrador'
        check (estado in ('borrador', 'enviado_sence', 'aprobado', 'ejecutando', 'liquidado')),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists cursos_sence_estado_idx on public.cursos_sence (estado);

create or replace function public.set_updated_at_cursos_sence()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists cursos_sence_updated_at on public.cursos_sence;

create trigger cursos_sence_updated_at
before update on public.cursos_sence
for each row
execute function public.set_updated_at_cursos_sence();
