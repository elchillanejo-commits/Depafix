create extension if not exists vector;

create table if not exists public.coach_shopify (
    id bigint generated by default as identity primary key,
    contenido text not null,
    metadata jsonb not null default '{}'::jsonb,
    embedding vector(384) not null,
    hash_origen text,
    created_at timestamptz not null default now()
);

create table if not exists public.coach_rrss (
    id bigint generated by default as identity primary key,
    contenido text not null,
    metadata jsonb not null default '{}'::jsonb,
    embedding vector(384) not null,
    hash_origen text,
    created_at timestamptz not null default now()
);

create index if not exists coach_shopify_embedding_idx
    on public.coach_shopify using hnsw (embedding vector_cosine_ops);

create index if not exists coach_rrss_embedding_idx
    on public.coach_rrss using hnsw (embedding vector_cosine_ops);

alter table public.coach_shopify add column if not exists hash_origen text;
alter table public.coach_rrss add column if not exists hash_origen text;

create unique index if not exists coach_shopify_hash_origen_idx
    on public.coach_shopify (hash_origen);

create unique index if not exists coach_rrss_hash_origen_idx
    on public.coach_rrss (hash_origen);
